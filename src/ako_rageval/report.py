def _pct(x: float) -> str:
    return f"{x:.3f}"


def _bar(x: float) -> str:
    return f'<span class="bar"><i style="width:{max(0.0, min(1.0, x)) * 100:.0f}%"></i></span>'


def _docs(ids: Sequence[str], relevant: set[str]) -> str:
    parts = [f'<code class="ok">{escape(d)}</code>' if d in relevant else f"<code>{escape(d)}</code>" for d in ids]
    return " ".join(parts) or "&mdash;"


def render_html(runs: Sequence[RunResult], generation: GenerationResult | None = None, lang: str = "en", version: str = "") -> str:
    """Render a report for one or more runs (best first) and optional answer evaluation."""
    if lang not in LABELS:
        raise ValueError(f"lang must be one of {', '.join(LABELS)}")
    t = LABELS[lang]
    out: list[str] = []
    if runs:
        k = runs[0].primary_k
        out.append(f"<h2>{escape(t['comparison'])}</h2><p class='note'>{escape(t['comparison_note'].format(k=k))}</p>")
        out.append("<table><thead><tr>")
        heads = [t["config"], t["chunks"], f"hit@{k}", f"recall@{k}", f"precision@{k}", "mrr", f"ndcg@{k}"]
        out.append("".join(f"<th>{escape(h)}</th>" for h in heads))
        out.append("</tr></thead><tbody>")
        for r in runs:
            s = r.summary
            kk = r.primary_k
            out.append(
                f"<tr><td><code>{escape(r.label)}</code></td><td class='num'>{r.num_chunks}</td>"
                f"<td class='num'>{_pct(s[f'hit@{kk}'])}</td><td class='num'>{_pct(s[f'recall@{kk}'])}</td>"
                f"<td class='num'>{_pct(s[f'precision@{kk}'])}</td><td class='num'>{_pct(s['mrr'])}</td>"
                f"<td class='num'>{_pct(s[f'ndcg@{kk}'])}{_bar(s[f'ndcg@{kk}'])}</td></tr>"
            )
        out.append("</tbody></table>")

        best = runs[0]
        out.append(f"<h2>{escape(t['best'])}</h2><p class='note'><code>{escape(best.label)}</code></p>")
        out.append("<table><thead><tr>")
        out.append("".join(f"<th>{escape(h)}</th>" for h in [t["query"], t["question"], t["relevant"], t["retrieved"].format(k=best.primary_k), f"recall@{best.primary_k}"]))
        out.append("</tr></thead><tbody>")
        for q in best.queries:
            rel = set(q.relevant)
            top = q.retrieved[: best.primary_k]
            out.append(
                f"<tr><td><code>{escape(q.id)}</code></td><td dir='auto'>{escape(q.question)}</td>"
                f"<td>{_docs(q.relevant, rel)}</td><td>{_docs(top, rel)}</td>"
                f"<td class='num'>{_pct(q.metrics[f'recall@{best.primary_k}'])}</td></tr>"
            )
        out.append("</tbody></table>")

        fails = best.failures()
        out.append(f"<h2>{escape(t['failures'].format(k=best.primary_k))}</h2>")
        if not fails:
            out.append(f"<p class='note'>{escape(t['no_failures'].format(k=best.primary_k))}</p>")
        else:
            out.append("<table><tbody>")
            for q in fails:
                out.append(f"<tr><td><code>{escape(q.id)}</code></td><td dir='auto'>{escape(q.question)}</td><td class='bad'>{_docs(q.relevant, set())}</td></tr>")
            out.append("</tbody></table>")

    if generation is not None:
        out.append(f"<h2>{escape(t['answers'])}</h2><p class='note'>{escape(t['answers_note'])}</p>")
        out.append("<table><tbody>")
        for key, value in generation.summary.items():
            shown = f"{int(value)}" if key == "answered" else _pct(value)
            label = t["answered"] if key == "answered" else t["coverage"] if key == "coverage" else key
            out.append(f"<tr><th>{escape(label)}</th><td class='num'>{shown}</td></tr>")
        out.append("</tbody></table><br>")
        out.append("<table><thead><tr>" + "".join(f"<th>{escape(h)}</th>" for h in [t["query"], t["answer"], "token_f1", "token_recall", "groundedness"]) + "</tr></thead><tbody>")
        for a in generation.queries:
            f1 = "&mdash;" if a.token_f1 is None else _pct(a.token_f1)
            rc = "&mdash;" if a.token_recall is None else _pct(a.token_recall)
            gr = "&mdash;" if a.groundedness is None else _pct(a.groundedness)
            out.append(f"<tr><td><code>{escape(a.id)}</code></td><td dir='auto'>{escape(a.answer)}</td><td class='num'>{f1}</td><td class='num'>{rc}</td><td class='num'>{gr}</td></tr>")
        out.append("</tbody></table>")

    footer = escape(t["footer"]) + (f" {escape(version)}" if version else "")
    return (
        f"<!doctype html><html lang='{t['lang']}' dir='{t['dir']}'><head><meta charset='utf-8'>"
        f"<meta name='viewport' content='width=device-width,initial-scale=1'><title>{escape(t['title'])}</title>"
        f"<style>{CSS}</style></head><body><h1>{escape(t['title'])}</h1>{''.join(out)}<footer>{footer}</footer></body></html>"
    )


def to_json(runs: Sequence[RunResult], generation: GenerationResult | None = None) -> str:
    payload: dict[str, object] = {"runs": [r.to_dict() for r in runs]}
    if generation is not None:
        payload["generation"] = generation.to_dict()
    return json.dumps(payload, ensure_ascii=False, indent=2)
